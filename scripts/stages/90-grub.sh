#!/usr/bin/env bash
# Phase 5.1 — GRUB, built from source for i386-pc (legacy BIOS).
#
# The host has no grub package and no root, so the usual `grub-install
# /dev/nbd0` is not available.  Instead GRUB is compiled here, its i386-pc
# modules are placed in the guest tree, and the next stage embeds the boot
# sectors directly into a disk *file* with grub-bios-setup — which, unlike
# losetup and mount, is perfectly happy to work on a regular file.
#
# Direct kernel boot (`./lfn boot`) does not need any of this.  This stage is
# what makes the disk bootable on real hardware, or in QEMU without -kernel.
source "$LFN_PROJ/scripts/lib/prologue.sh"

tarball=$(fetch "https://ftp.gnu.org/gnu/grub/grub-$GRUB_VER.tar.xz")
srcdir=$(extract "$tarball")

# GRUB 2.12's generated Makefile depends on this intentionally empty input,
# but the release tarball omits the empty file.  Out-of-tree builds otherwise
# stop late with "No rule to make target .../extra_deps.lst".
[[ -e "$srcdir/grub-core/extra_deps.lst" ]] ||
  install -m644 /dev/null "$srcdir/grub-core/extra_deps.lst"

# grub-bios-setup normally infers its root device from the directory holding
# boot.img/core.img.  That cannot match a regular-file disk image which is not
# mounted.  When the caller explicitly disabled filesystem probing, fall back
# to the already-opened destination instead.  Opening it a second time keeps
# the normal cleanup path (which closes root_dev and dest_dev separately).
if ! grep -q 'LFN regular-file target' "$srcdir/util/setup.c"; then
  patch -d "$srcdir" -p1 <<'PATCH'
--- a/util/setup.c
+++ b/util/setup.c
@@ -353,8 +353,19 @@ SETUP (const char *dir,
       }
     if (!root_dev)
       {
-	grub_util_error ("guessing the root device failed, because of `%s'",
-			 grub_errmsg);
+	/* LFN regular-file target: an unmounted image cannot contain DIR.  */
+	if (!fs_probe)
+	  {
+	    grub_errno = GRUB_ERR_NONE;
+	    root = xstrdup (dest);
+	    root_dev = grub_device_open (dest);
+	    if (!root_dev)
+	      grub_util_error ("opening explicit root device failed: %s",
+			       grub_errmsg);
+	  }
+	else
+	  grub_util_error ("guessing the root device failed, because of `%s'",
+			   grub_errmsg);
       }
     grub_util_info ("guessed root_dev `%s' from "
 		    "dir `%s'", root_dev->disk->name, dir);
PATCH
fi

hostdir="$LFN_WORK/grub-host"       # GRUB's own tools, for host use only
bdir="$BUILD/grub"
rm -rf "$bdir" "$hostdir"; mkdir -p "$bdir"; cd "$bdir"

# GRUB's target code is freestanding (-nostdlib, its own linker script), so a
# 32-bit target compiler works without any 32-bit libc on the host.
step "configure grub $GRUB_VER for i386-pc"
"$srcdir/configure" \
  --prefix="$hostdir" \
  --target=i386 \
  --with-platform=pc \
  --disable-werror \
  --disable-nls \
  --disable-efiemu \
  --disable-device-mapper \
  --disable-libzfs \
  --disable-grub-mkfont \
  --disable-grub-themes \
  --disable-grub-mount \
  TARGET_CC="gcc -m32" \
  TARGET_CFLAGS="-Os -ffreestanding -fno-stack-protector" \
  TARGET_CPPFLAGS="-ffreestanding" \
  TARGET_LDFLAGS="-nostdlib" \
  || die "grub configure failed"

make -j"$JOBS" || die "grub build failed"
make install || die "grub install failed"

for t in grub-mkimage grub-mkrelpath; do
  [[ -x "$hostdir/bin/$t" ]] || die "grub did not build $t"
done
[[ -x "$hostdir/sbin/grub-bios-setup" ]] || die "grub did not build grub-bios-setup"
[[ -f "$hostdir/lib/grub/i386-pc/boot.img" ]] || die "no i386-pc boot.img"
step "grub tools in ${hostdir#$LFN_WORK/}, $(ls "$hostdir"/lib/grub/i386-pc/*.mod | wc -l) modules"

# ------------------------------------------------- modules into the guest ----
install -d "$LFN/boot/grub/i386-pc"
cp -a "$hostdir"/lib/grub/i386-pc/*.mod \
      "$hostdir"/lib/grub/i386-pc/*.lst \
      "$hostdir"/lib/grub/i386-pc/*.img "$LFN/boot/grub/i386-pc/" 2>/dev/null || true

# ------------------------------------------------------------- grub.cfg ------
# The whole session runs on the serial line, GRUB included: with -nographic
# there is no VGA console to read a menu on.
rel=$(cat "$LFN_WORK/.kernel-release" 2>/dev/null || echo unknown)
install -Dm644 /dev/stdin "$LFN/boot/grub/grub.cfg" <<EOF
# Generated by LFN stage 90-grub.
set timeout=3
set default=0

serial --unit=0 --speed=115200
terminal_input  serial console
terminal_output serial console

insmod part_msdos
insmod ext2
insmod biosdisk

# Drives count from 0, partitions from 1: (hd0,msdos1) is /dev/vda1.
set root='(hd0,msdos1)'

menuentry 'Linux From Nothing ($rel)' {
    linux /boot/bzImage root=/dev/vda1 rw rootfstype=ext4 rootwait console=ttyS0,115200 panic=10
}

menuentry 'Linux From Nothing — rescue shell (no init)' {
    linux /boot/bzImage root=/dev/vda1 rw rootfstype=ext4 rootwait console=ttyS0,115200 init=/bin/zsh
}

menuentry 'Linux From Nothing — verbose boot' {
    linux /boot/bzImage root=/dev/vda1 rw rootfstype=ext4 rootwait console=ttyS0,115200 earlyprintk=serial,ttyS0 ignore_loglevel
}
EOF

drop_build "$bdir"
ok "grub $GRUB_VER built; modules and grub.cfg placed in the guest tree"
